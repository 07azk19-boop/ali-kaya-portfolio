/* =========================================================
   OPEN EVENT
========================================================= */

function openEvent(eventId) {

    const event =
        eventData[eventId];

    if (!event) {
        return;
    }


    const content =
        event[currentLanguage];


    /*
       Guests
    */

    let guestsHTML = "";


    if (content.guests.length > 0) {

        guestsHTML = `

            <div class="modal-guests-title">
                ${content.guestsTitle}
            </div>

            <div class="modal-guests">

                ${content.guests.map(guest => `

                    <div class="modal-guest">

                        <strong>
                            ${guest[0]}
                        </strong>

                        <span>
                            ${guest[1]}
                        </span>

                    </div>

                `).join("")}

            </div>

        `;

    }



    /*
       Images
    */

    const imagesHTML =
        event.images.map(image => `

            <div class="modal-image-wrapper">

                <img
                    src="${image}"
                    alt="${content.title}"
                >

            </div>

        `).join("");



    /*
       Modal
    */

    modalContent.innerHTML = `

        <div class="modal-kicker">
            ${event.date}
        </div>

        <h2 class="modal-title">
            ${content.title}
        </h2>

        <p class="modal-subtitle">
            ${content.subtitle}
        </p>

        <p class="modal-description">
            ${content.description}
        </p>

        ${guestsHTML}

        <div class="modal-images">

            ${imagesHTML}

        </div>

    `;


    modal.classList.add("active");

    document.body.classList.add("modal-open");

}



/* =========================================================
   CLOSE EVENT
========================================================= */

function closeEvent() {

    modal.classList.remove("active");

    document.body.classList.remove("modal-open");

}



/* =========================================================
   CARD EVENTS
========================================================= */

eventCards.forEach(card => {

    card.addEventListener("click", () => {

        const eventId =
            card.dataset.event;

        openEvent(eventId);

    });

});



/* =========================================================
   LANGUAGE BUTTON
========================================================= */

languageToggle.addEventListener(
    "click",
    () => {

        const newLanguage =
            currentLanguage === "tr"
                ? "en"
                : "tr";

        setLanguage(newLanguage);

    }
);



/* =========================================================
   CLOSE BUTTON
========================================================= */

modalClose.addEventListener(
    "click",
    closeEvent
);



/* =========================================================
   BACKGROUND CLICK
========================================================= */

modal.addEventListener(
    "click",
    event => {

        if (event.target === modal) {

            closeEvent();

        }

    }
);



/* =========================================================
   ESC
========================================================= */

document.addEventListener(
    "keydown",
    event => {

        if (event.key === "Escape") {

            closeEvent();

        }

    }
);



